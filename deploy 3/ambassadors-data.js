(function(){
  const pad = n => String(n).padStart(3,'0');
  const slugify = s => s.toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g,'')
    .replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'') || 'ambassador';
  const initials = s => {
    const parts = s.split(/\s+/).filter(p => /[A-Za-z\u00C0-\u024F]/.test(p[0]||''));
    if (!parts.length) return '★';
    return (parts[0][0] + (parts.length>1 ? parts[parts.length-1][0] : '')).toUpperCase();
  };
  const parseD = s => typeof s === "string" ? s.trim().split("\n").filter(l=>l.trim()).map(l=>l.split("\u00a6")) : (s||[]);
  const D = [].concat(parseD(window.YSP_DETAILS_1), parseD(window.YSP_DETAILS_2), parseD(window.YSP_DETAILS_3), parseD(window.YSP_DETAILS_4));
  const clean = s => { s = (s||'').trim(); return /^(n\/?a|na|nil+|none|no|not applicable|yes|\.|-|_|nan|non)$/i.test(s) ? '' : s; };
  const linkOf = s => { s = (s||'').trim(); if(!/linkedin\.com|^https?:\/\//i.test(s)) return ''; return s.startsWith('http') ? s : 'https://' + s.replace(/^\/+/,''); };
  const C = ((window.YSP_COUNTRIES||"").trim().split("\n").map(s=>s.trim()));
  const REG = {}; Object.entries(window.YSP_REGIONS||{}).forEach(([r,cs]) => cs.forEach(c => REG[c] = r));
  const seenSlug = {};
  const list = [];
  window.YSP_ROSTER_RAW.trim().split('\n').forEach((line, i) => {
    const [nameRaw, prefRaw] = line.split('|');
    const name = (nameRaw||'').trim();
    if (!name) return;
    const pref = (prefRaw||'').trim();
    const d = D[i] || [];
    let slug = slugify(name);
    if (seenSlug[slug]) { slug = slug + '-' + (++seenSlug[slug]); } else { seenSlug[slug] = 1; }
    list.push({
      name,
      goesBy: pref && pref.toLowerCase() !== name.toLowerCase() ? pref : '',
      slug,
      initials: initials(name),
      cohort: 'Founding Cohort 2026',
      role: 'Global Youth Ambassador',
      appointed: 'August 2026',
      gender: clean(d[0]),
      languages: clean(d[1]),
      education: clean(d[2]),
      field: clean(d[3]),
      linkedin: linkOf(d[4]),
      pathway: clean(d[5]) || 'Global Ambassador',
      country: clean(C[i]||''),
      region: REG[clean(C[i]||'')] || ''
    });
  });
  list.sort((a,b) => a.name.localeCompare(b.name, 'en'));
  list.forEach((a,i) => { a.id = 'YSP-GA-26-' + pad(i+1); });
  window.YSP_AMBASSADORS = list;
})();
